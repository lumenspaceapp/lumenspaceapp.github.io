// Copies Lumi's help guide (js/help-kb.js) into the AI worker as plain text, so the AI answers from the same facts.
// Run after editing the guide:  node tools/export-kb.mjs
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
const root = new URL("..", import.meta.url);
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(readFileSync(new URL("js/features.js", root), "utf8"), ctx); // pages on/off
vm.runInContext(readFileSync(new URL("js/help-kb.js", root), "utf8"), ctx);
const strip = h => h.replace(/<br\s*\/?>/g, "\n").replace(/<[^>]+>/g, "").replace(/&gt;/g, ">").replace(/&lt;/g, "<").replace(/&amp;/g, "&");
const text = ctx.window.HelpKB.KB.map(e => `## ${e.t}\n${strip(e.a)}${e.act?.length ? `\nUseful actions: ${e.act.join(", ")}` : ""}`).join("\n\n");
writeFileSync(new URL("worker/src/kb.js", root), `// Generated by tools/export-kb.mjs from js/help-kb.js. Do not edit by hand.\nexport default ${JSON.stringify(text)};\n`);
console.log(`exported ${ctx.window.HelpKB.KB.length} topics, ${text.length} chars`);
